    public function run(): void
    {
        foreach (self::RESTAURANTS as $slug => $locales) {
            Restaurant::where('slug', $slug)->get()->each(fn (Restaurant $r) => $this->merge(
                $r,
                array_map(fn ($description) => ['description' => $description], $locales),
            ));
        }

        foreach (self::CATEGORIES as $name => $locales) {
            Category::where('name', $name)->get()->each(fn (Category $c) => $this->merge(
                $c,
                array_map(fn ($t) => ['name' => $t[0], 'description' => $t[1]], $locales),
            ));
        }

        foreach (self::PRODUCTS as $name => $locales) {
            Product::where('name', $name)->get()->each(fn (Product $p) => $this->merge(
                $p,
                array_map(fn ($t) => ['name' => $t[0], 'description' => $t[1], 'ingredients' => $t[2]], $locales),
            ));
        }
    }

    /**
     * Add these languages to the model's translations, keeping the others.
     *
     * @param  array<string, array<string, mixed>>  $locales
     */
    private function merge(Restaurant|Category|Product $model, array $locales): void
    {
        $model->translations = array_replace($model->translations ?? [], $locales);
        $model->saveQuietly();
    }
